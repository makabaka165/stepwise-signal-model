function [n_elem, ratio] = complexity_values_local(evidence)
n_elem = 2080;
ratio = get_key_metric_value_local(evidence, 'Stage6 full4d upper-bound comparison', 'complexity_ratio_full4d_over_pair2d');
if ~isfinite(ratio)
    ratio = NaN;
end
end

function [stage5_worst, false_high, full_role] = limitation_values_local(evidence)
stage5_worst = get_key_metric_value_local(evidence, 'Stage5 coherence stress', 'worst_case_joint_success_pair2d_white');
false_high = get_key_metric_value_local(evidence, 'Stage5 coherence stress', 'max_false_high_like_rate');
full_role = get_key_metric_text_local(evidence, 'Stage6 full4d upper-bound comparison', 'full4d_recommended_role');
if isempty(full_role)
    full_role = 'unknown';
end
end

function value = get_key_metric_value_local(evidence, stage_name, metric)
tbl = evidence.final_key_metrics_table;
mask = strcmp(string(tbl.stage), string(stage_name)) & strcmp(string(tbl.metric), string(metric));
if any(mask)
    value = tbl.metric_value(find(mask, 1, 'first'));
else
    value = NaN;
end
end

function text = get_key_metric_text_local(evidence, stage_name, metric)
tbl = evidence.final_key_metrics_table;
mask = strcmp(string(tbl.stage), string(stage_name)) & strcmp(string(tbl.metric), string(metric));
if any(mask)
    text = char(tbl.metric_text(find(mask, 1, 'first')));
else
    text = '';
end
end

function md = table_to_markdown_local(tbl)
if isempty(tbl)
    md = '_No rows._';
    return;
end
names = tbl.Properties.VariableNames;
lines = cell(height(tbl) + 2, 1);
lines{1} = ['| ' strjoin(names, ' | ') ' |'];
lines{2} = ['| ' strjoin(repmat({'---'}, 1, numel(names)), ' | ') ' |'];
for iRow = 1:height(tbl)
    vals = cell(1, numel(names));
    for iCol = 1:numel(names)
        vals{iCol} = value_to_text_local(tbl.(names{iCol})(iRow));
    end
    lines{iRow + 2} = ['| ' strjoin(vals, ' | ') ' |'];
end
md = strjoin(lines, newline);
end

function text = value_to_text_local(value)
if iscell(value)
    text = char(value{1});
elseif isstring(value)
    text = char(value);
elseif isnumeric(value) || islogical(value)
    if isfinite(value)
        text = sprintf('%.12g', value);
    else
        text = 'NaN';
    end
else
    text = char(string(value));
end
text = strrep(text, '|', '/');
end

function md = missing_files_markdown_local(missing_files)
if isempty(missing_files)
    md = '_None._';
    return;
end
lines = cell(numel(missing_files), 1);
for idx = 1:numel(missing_files)
    lines{idx} = ['- ' missing_files{idx}];
end
md = strjoin(lines, newline);
end

function write_text_local(path, text)
fid = fopen(path, 'w');
if fid < 0
    error('write_step11_1_final_docs:OpenFailed', 'Could not open %s.', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', text);
clear cleanup;
end

function text = join_lines_local(lines)
text = strjoin(lines, newline);
end
