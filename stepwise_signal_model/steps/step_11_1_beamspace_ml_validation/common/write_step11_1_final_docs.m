function doc_paths = write_step11_1_final_docs(evidence, result_dir)
%WRITE_STEP11_1_FINAL_DOCS Write Stage7 final Markdown evidence documents.

if nargin ~= 2
    error('write_step11_1_final_docs:InvalidInputCount', 'evidence and result_dir are required.');
end
if ~exist(result_dir, 'dir')
    mkdir(result_dir);
end

doc_specs = { ...
    '00_FINAL_STEP11_1_ONE_PAGE_SUMMARY.md', @doc_one_page_local; ...
    '01_ALGORITHM_FORMULATION.md', @doc_formulation_local; ...
    '02_ALGORITHM_FLOW.md', @doc_flow_local; ...
    '03_EXPERIMENT_EVIDENCE_TABLES.md', @doc_evidence_tables_local; ...
    '04_COMPLEXITY_AND_BEAMSPACE_DIMENSION.md', @doc_complexity_local; ...
    '05_COMPARISON_WITH_STEP7_BEAM_SMOOTHING.md', @doc_step7_compare_local; ...
    '06_LIMITATIONS_AND_BOUNDARY_CASES.md', @doc_limitations_local; ...
    '07_THESIS_WRITING_OUTLINE.md', @doc_outline_local};

doc_paths = cell(size(doc_specs, 1), 1);
for idx = 1:size(doc_specs, 1)
    out_path = fullfile(result_dir, doc_specs{idx, 1});
    text = doc_specs{idx, 2}(evidence);
    write_text_local(out_path, text);
    doc_paths{idx} = out_path;
end
end

