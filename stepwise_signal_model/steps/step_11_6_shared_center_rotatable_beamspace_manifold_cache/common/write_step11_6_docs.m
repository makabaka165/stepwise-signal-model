function doc_paths = write_step11_6_docs(result_dir, keypoints, stage1_summary, stage2_summary, stage3_summary, stage4_summary, cache_metadata)
%WRITE_STEP11_6_DOCS Write Step11.6 Markdown reports.

doc_names = { ...
    '00_STEP11_6_ONE_PAGE_SUMMARY.md'; ...
    '01_THEORY_ROTATION_EQUIVALENCE.md'; ...
    '02_CACHE_ALGORITHM_FLOW.md'; ...
    '03_MANIFOLD_EQUIVALENCE_RESULTS.md'; ...
    '04_SEARCH_CONSISTENCY_RESULTS.md'; ...
    '05_RUNTIME_AND_MEMORY_RESULTS.md'; ...
    '06_LIMITATIONS_AND_USAGE_BOUNDARY.md'; ...
    '07_THESIS_WRITING_TEXT.md'};
doc_paths = cell(numel(doc_names), 1);
for idx = 1:numel(doc_names)
    doc_paths{idx} = fullfile(result_dir, doc_names{idx});
end

write_text_local(doc_paths{1}, one_page_text_local(keypoints));
write_text_local(doc_paths{2}, theory_text_local());
