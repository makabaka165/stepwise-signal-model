function write_text_local(path, text)
fid = fopen(path, 'w', 'n', 'UTF-8');
if fid < 0
    error('write_step11_6_docs:OpenFailed', 'Could not open %s.', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', text);
clear cleanup;
end

function value = numeric_value_local(T, field, fallback)
value = fallback;
if istable(T) && ismember(field, T.Properties.VariableNames) && height(T) >= 1
    value = T.(field)(1);
elseif isstruct(T) && isfield(T, field)
    value = T.(field);
end
if ~(isnumeric(value) && isscalar(value) && isfinite(value))
    value = fallback;
end
end

function value = text_field_local(T, field)
raw = T.(field);
if iscell(raw)
    value = raw{1};
elseif isstring(raw)
    value = char(raw(1));
elseif ischar(raw)
    value = raw;
else
    value = char(string(raw(1)));
end
end
