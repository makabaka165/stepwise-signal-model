function doc_paths = write_step11_5_stage3_docs(result_dir, keypoints, alt_summary_table, repeat_summary_table, branch_trial_table, branch_summary_table)
%WRITE_STEP11_5_STAGE3_DOCS Write Stage3 required enhancement Markdown files.

if nargin < 6
    error('write_step11_5_stage3_docs:NotEnoughInputs', ...
        'result_dir, keypoints, alt_summary_table, repeat_summary_table, branch_trial_table, and branch_summary_table are required.');
end
if exist(result_dir, 'dir') ~= 7
    mkdir(result_dir);
end
doc_paths = {};
doc_paths{end + 1} = write_text_local(fullfile(result_dir, '00_STEP11_5_STAGE3_ONE_PAGE_SUMMARY.md'), one_page_local(keypoints));
doc_paths{end + 1} = write_text_local(fullfile(result_dir, '01_ALTERNATIVE_SPLIT_RECHECK.md'), alt_split_local(keypoints, alt_summary_table));
doc_paths{end + 1} = write_text_local(fullfile(result_dir, '02_REPEAT_SEED_METKL_RECHECK.md'), repeat_seed_local(keypoints, repeat_summary_table));
doc_paths{end + 1} = write_text_local(fullfile(result_dir, '03_TARGETED_BRANCH_RECHECK.md'), targeted_branch_local(keypoints, branch_trial_table, branch_summary_table));
doc_paths{end + 1} = write_text_local(fullfile(result_dir, '04_STAGE2_TO_STAGE3_CONCLUSION.md'), conclusion_local(keypoints));
doc_paths{end + 1} = write_text_local(fullfile(result_dir, '05_THESIS_WRITING_TEXT.md'), thesis_local(keypoints));
end

