function text = conclusion_local(k)
if k.stage3_required_enhancement_pass_flag == 1
    conclusion = 'Stage3 supports keeping Stage2 selected C05 as the Step11.5 positive adaptive enhancement.';
else
    conclusion = 'Stage3 found at least one failed or limited enhancement check. Keep the Stage2 positive result but document the Stage3 boundary explicitly.';
end
text = strjoin({ ...
    '# Stage2 To Stage3 Conclusion', ...
    '', ...
    'Stage3 does not reselect policy parameters and does not modify Step11.1, Step11.2, Step11.3, or Step11.4. It validates only the already selected Stage2 C05 policy.', ...
    '', ...
    conclusion, ...
    '', ...
    sprintf('stage3_required_enhancement_pass_flag = %.0f', k.stage3_required_enhancement_pass_flag), ...
    sprintf('stage3_recommended_next_step = `%s`', k.stage3_recommended_next_step) ...
    }, newline);
end

function text = thesis_local(k)
if k.stage3_required_enhancement_pass_flag == 1
    para = ['Step11.5 Stage3 further validated the Stage2 selected C05 adaptive policy by testing alternative data splits, ', ...
        'larger Metkl with repeated seeds, and targeted safety-branch behavior. The alternative split and repeat-seed checks kept the same fixed C05 parameters and did not use target truth in search-center, candidate, topK, or policy decisions. ', ...
        'The targeted branch checks showed that BOUNDARY and ILL_CONDITIONED branches can be triggered and produce non-high-confidence safety outputs. ', ...
        'Therefore the Stage2 C05 policy can be retained as a positive adaptive enhancement after the Step11.3 fixed topK3 beamspace ML baseline.'];
else
    para = ['Step11.5 Stage3 kept the Stage2 selected C05 policy fixed and ran the required robustness and safety-branch rechecks. ', ...
        'At least one Stage3 check did not fully pass, so the Stage2 positive result should be reported together with the failed or limited Stage3 boundary condition.'];
end
text = strjoin({ ...
    '# Step11.5 Stage3 Thesis Writing Text', ...
    '', ...
    para ...
    }, newline);
end

function path = write_text_local(path, text)
fid = fopen(path, 'w', 'n', 'UTF-8');
if fid < 0
    error('write_step11_5_stage3_docs:OpenFailed', 'Could not open %s.', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', text);
clear cleanup;
end

function text = table_to_markdown_local(T)
if isempty(T)
    text = '_No rows._';
    return;
end
vars = T.Properties.VariableNames;
lines = cell(height(T) + 2, 1);
lines{1} = ['| ', strjoin(vars, ' | '), ' |'];
lines{2} = ['| ', strjoin(repmat({'---'}, 1, numel(vars)), ' | '), ' |'];
for iRow = 1:height(T)
    parts = cell(1, numel(vars));
    for iVar = 1:numel(vars)
        parts{iVar} = value_to_text_local(T.(vars{iVar})(iRow));
    end
    lines{iRow + 2} = ['| ', strjoin(parts, ' | '), ' |'];
end
text = strjoin(lines, newline);
end

function text = value_to_text_local(value)
if iscell(value)
    text = char(value{1});
elseif isstring(value)
    text = char(value);
elseif islogical(value)
    text = sprintf('%d', value);
elseif isnumeric(value)
    text = sprintf('%.12g', value);
else
    text = char(value);
end
end
