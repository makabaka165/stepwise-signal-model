function text = metkl30_interpretation_local(k)
if k.metkl30_repeat_pass_flag == 1
    text = 'Metkl=30 repeat-seed evidence strengthens the Stage2/Stage3 C05 positive result under larger representative-scenario sampling.';
else
    text = 'Metkl=30 repeat-seed evidence does not strengthen the Stage2/Stage3 C05 claim. The failed seed group and metric should be reported.';
end
end

function text = illcond_interpretation_local(k)
if k.illcond_real_stress_pass_flag == 1
    text = 'ILL_CONDITIONED was naturally triggered in real-search stress and passed the confidence safety checks.';
elseif k.illcond_guard_probe_pass_flag == 1
    text = 'ILL_CONDITIONED was not naturally triggered in real-search stress under the current fixed C05/W/grid/threshold setting. The deterministic guard probe remains only logic evidence and must not be described as real-search triggering.';
else
    text = 'Neither real-search stress nor deterministic guard probe fully validated the ILL_CONDITIONED branch. This remains a boundary limitation.';
end
end

function text = final_conclusion_local(k)
if k.stage3_supplementary_pass_flag == 1
    text = 'The supplementary evidence supports strengthening C05 as the final Step11.5 adaptive enhancement with both larger-sample robustness and real ill-conditioned branch triggering.';
elseif k.metkl30_repeat_pass_flag == 1 && k.illcond_guard_probe_pass_flag == 1
    text = 'The supplementary evidence strengthens C05 on Metkl=30 representative-scenario robustness, while keeping real ill-conditioned triggering as boundary/future work.';
else
    text = 'The supplementary evidence does not strengthen the existing Stage3 required validation conclusion.';
end
end

function text = boundary_statement_local(k)
if k.illcond_real_trigger_count == 0
    text = 'Because ill-conditioned real-search stress did not naturally trigger ILL_CONDITIONED, the thesis must not claim real-search triggering. It may only claim deterministic guard-probe validation of the safety logic.';
else
    text = 'Ill-conditioned real-search triggering occurred in this supplementary stress set; still report that the stress is branch-behavior evidence rather than representative-scene success evidence.';
end
end

function path = write_text_local(path, text)
fid = fopen(path, 'w', 'n', 'UTF-8');
if fid < 0
    error('write_step11_5_stage3_supplementary_docs:OpenFailed', 'Could not open %s.', path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', text);
clear cleanup;
end

function text = table_to_markdown_local(T)
if isempty(T)
    text = '_No rows._';
    return;
end
vars = T.Properties.VariableNames;
lines = cell(height(T) + 2, 1);
lines{1} = ['| ', strjoin(vars, ' | '), ' |'];
lines{2} = ['| ', strjoin(repmat({'---'}, 1, numel(vars)), ' | '), ' |'];
for iRow = 1:height(T)
    parts = cell(1, numel(vars));
    for iVar = 1:numel(vars)
        parts{iVar} = value_to_text_local(T.(vars{iVar})(iRow));
    end
    lines{iRow + 2} = ['| ', strjoin(parts, ' | '), ' |'];
end
text = strjoin(lines, newline);
end

function text = value_to_text_local(value)
if iscell(value)
    text = char(value{1});
elseif isstring(value)
    text = char(value);
elseif islogical(value)
    text = sprintf('%d', value);
elseif isnumeric(value)
    text = sprintf('%.12g', value);
else
    text = char(value);
end
end
