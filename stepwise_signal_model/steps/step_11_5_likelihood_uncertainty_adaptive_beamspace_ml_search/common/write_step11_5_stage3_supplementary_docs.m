if nargin < 7
    error('write_step11_5_stage3_supplementary_docs:NotEnoughInputs', ...
        'result_dir, keypoints, summaries, guard probe, and final recommendation are required.');
end
if exist(result_dir, 'dir') ~= 7
    mkdir(result_dir);
end
doc_paths = {};
doc_paths{end + 1} = write_text_local(fullfile(result_dir, '00_STEP11_5_STAGE3_SUPP_ONE_PAGE_SUMMARY.md'), one_page_local(keypoints));
