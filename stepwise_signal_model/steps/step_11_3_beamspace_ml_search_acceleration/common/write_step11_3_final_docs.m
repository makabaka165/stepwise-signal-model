function doc_paths = write_step11_3_final_docs(evidence, result_dir)
%WRITE_STEP11_3_FINAL_DOCS Write final Step11.3 Markdown evidence documents.

if exist(result_dir, 'dir') ~= 7
    mkdir(result_dir);
end

doc_specs = { ...
    '00_FINAL_STEP11_3_ONE_PAGE_SUMMARY.md', @one_page_summary_local; ...
    '01_ALGORITHM_LOGIC_AND_FORMULATION.md', @algorithm_formulation_local; ...
    '02_COARSE_TO_FINE_FLOW.md', @coarse_to_fine_flow_local; ...
    '03_STAGE_RESULTS_TABLES.md', @stage_results_tables_local; ...
    '04_COMPLEXITY_REDUCTION_ANALYSIS.md', @complexity_analysis_local; ...
    '05_FRONTEND_PRIOR_AND_BIAS_ROBUSTNESS.md', @frontend_bias_local; ...
    '06_LIMITATIONS_AND_USAGE_BOUNDARY.md', @limitations_local; ...
    '07_THESIS_WRITING_TEXT.md', @thesis_text_local};

doc_paths = cell(size(doc_specs, 1), 1);
for idx = 1:size(doc_specs, 1)
    out_path = fullfile(result_dir, doc_specs{idx, 1});
    lines = doc_specs{idx, 2}(evidence);
    write_lines_local(out_path, lines);
    doc_paths{idx} = out_path;
end
end

