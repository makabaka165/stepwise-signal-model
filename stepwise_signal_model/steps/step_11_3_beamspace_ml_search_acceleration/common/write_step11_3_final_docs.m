function lines = complexity_analysis_local(evidence)
m = final_metrics_local(evidence);
full_pairs = key_num_local(evidence.stage2_keypoints, 'full_fine_mean_num_pairs', NaN);
ctf_pairs = key_num_local(evidence.stage2_keypoints, 'coarse_to_fine_mean_num_pairs', NaN);
saved = 100 * (1 - ctf_pairs / max(full_pairs, eps));
lines = { ...
    '# Complexity reduction analysis'; ...
    ''; ...
    sprintf('Full fine candidates: `%s`.', m.full_pairs); ...
    ''; ...
    sprintf('Coarse-to-fine candidates: `%s`.', m.ctf_pairs); ...
    ''; ...
    sprintf('Reduction: `%s`.', m.reduction); ...
    ''; ...
    sprintf('The candidate scoring count is reduced by about %.1f%%.', saved); ...
    ''; ...
    'The coarse grid uses fewer candidates to locate the topK promising ML-score regions. The refine stage then searches only within local windows around those topK candidates. Every candidate is still scored by the same controlled pair2d DML score, so this is a search-complexity reduction rather than a different ML model.'};
end

