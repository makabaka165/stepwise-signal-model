function value = key_text_local(T, key, fallback)
if isempty(T)
    value = fallback;
    return;
end
mask = strcmp(T.keypoint, string(key));
if ~any(mask)
    value = fallback;
else
    value = char(T.value(find(mask, 1)));
end
if isempty(value)
    value = fallback;
end
end

function value = key_num_local(T, key, fallback)
value = str2double(key_text_local(T, key, 'NaN'));
if ~isfinite(value)
    value = fallback;
end
end

function out = value_or_missing_local(in)
if isempty(in)
    out = 'missing';
else
    out = in;
end
end

function lines = append_missing_local(lines, evidence)
lines{end + 1, 1} = '';
lines{end + 1, 1} = '## Missing source files';
lines{end + 1, 1} = '';
if isempty(evidence.missing_files)
    lines{end + 1, 1} = 'None.';
else
    missing_lines = cell(numel(evidence.missing_files), 1);
    for idx = 1:numel(evidence.missing_files)
        missing_lines{idx} = sprintf('- %s', evidence.missing_files{idx});
    end
    lines = [lines; missing_lines];
end
end

function write_lines_local(path_in, lines)
fid = fopen(path_in, 'w');
if fid < 0
    error('write_step11_3_final_docs:OpenFailed', 'Could not open %s', path_in);
end
cleanup = onCleanup(@() fclose(fid));
for idx = 1:numel(lines)
    fprintf(fid, '%s\n', lines{idx});
end
clear cleanup;
end
